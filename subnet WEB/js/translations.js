let currentLang = 'ku'; // Kurdish Sorani is default

function t(key, replacements = {}) {
  const dict = Translations[currentLang] || Translations.ku;
  let text = dict[key] || Translations.en[key] || key;
  for (const [k, v] of Object.entries(replacements)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return text;
}

function setLanguage(lang) {
  if (Translations[lang]) {
    currentLang = lang;
    try {
      localStorage.setItem('skplus_lang', lang);
    } catch (e) {}
    document.documentElement.lang = lang === 'ku' ? 'ckb' : 'en';
    document.documentElement.dir = lang === 'ku' ? 'rtl' : 'ltr';
    document.body.classList.toggle('lang-kurdish', lang === 'ku');
    document.body.classList.toggle('lang-english', lang === 'en');
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }
}

function getCurrentLang() {
  return currentLang;
}

if (typeof window !== 'undefined') {
  window.Translations = Translations;
  window.t = t;
  window.setLanguage = setLanguage;
  window.getCurrentLang = getCurrentLang;
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { Translations, t, setLanguage, getCurrentLang };
}

